"""Private storage for checklist issue photos.

Uploaded images are fully decoded and re-encoded with Pillow. This strips EXIF/GPS,
ICC tricks, trailing polyglot data and anything else embedded in the file, and it
guarantees the stored bytes really are the declared image type. Files live outside
any public web root under a random, non-guessable key and are served only through
a permission-checked view.
"""
import io
import os
import secrets
from pathlib import Path

from django.conf import settings
from django.core.exceptions import ValidationError
from django.utils.translation import gettext as _
from PIL import Image, ImageOps, UnidentifiedImageError

Image.MAX_IMAGE_PIXELS = 40_000_000  # refuse decompression bombs

FORMATS = {"JPEG": ("image/jpeg", "jpg"), "PNG": ("image/png", "png"), "WEBP": ("image/webp", "webp")}


def storage_root():
    root = Path(settings.PRIVATE_UPLOAD_ROOT)
    root.mkdir(parents=True, exist_ok=True)
    return root


def path_for(key):
    # keys are generated by us; still refuse anything path-like
    if "/" in key or "\\" in key or key.startswith("."):
        raise ValueError("bad storage key")
    return storage_root() / key


def prepare_image(uploaded):
    """Validate and sanitize an uploaded image. Returns (bytes, content_type, ext).

    Raises ValidationError with a user-facing message; nothing is written.
    """
    max_bytes = settings.ISSUE_PHOTO_MAX_BYTES
    if uploaded.size > max_bytes:
        raise ValidationError(
            {"photo": _("The photo is too large. The limit is %(mb)s MB.") % {"mb": max_bytes // (1024 * 1024)}}
        )
    raw = uploaded.read(max_bytes + 1)
    if len(raw) > max_bytes:
        raise ValidationError({"photo": _("The photo is too large.")})
    try:
        with Image.open(io.BytesIO(raw)) as probe:
            fmt = probe.format
            probe.verify()
        if fmt not in FORMATS:
            raise ValidationError({"photo": _("Use a JPEG, PNG or WebP image.")})
        with Image.open(io.BytesIO(raw)) as img:
            img.load()
            img = ImageOps.exif_transpose(img)
            if fmt == "JPEG" and img.mode not in ("RGB", "L"):
                img = img.convert("RGB")
            out = io.BytesIO()
            save_kwargs = {"quality": 88} if fmt in ("JPEG", "WEBP") else {"optimize": True}
            img.save(out, format=fmt, **save_kwargs)  # no exif/icc passed -> stripped
    except ValidationError:
        raise
    except (UnidentifiedImageError, OSError, SyntaxError, ValueError, Image.DecompressionBombError):
        raise ValidationError({"photo": _("That file is not a readable JPEG, PNG or WebP image.")})
    content_type, ext = FORMATS[fmt]
    return out.getvalue(), content_type, ext


def write_private(data, ext):
    key = f"{secrets.token_urlsafe(32)}.{ext}"
    path = path_for(key)
    tmp = path.with_suffix(path.suffix + ".part")
    with open(tmp, "xb") as fh:
        fh.write(data)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)
    return key


def delete_private(key):
    try:
        path_for(key).unlink()
    except FileNotFoundError:
        pass
